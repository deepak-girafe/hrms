<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class Payroll extends Model
{
    protected $fillable = [

        /*
        |--------------------------------------------------------------------------
        | User
        |--------------------------------------------------------------------------
        */

        'user_id',

        'month',

        'year',

        /*
        |--------------------------------------------------------------------------
        | Payroll Meta
        |--------------------------------------------------------------------------
        */

        'salary_month',

        'working_days',

        'salary_date',

        'payment_status',

        /*
        |--------------------------------------------------------------------------
        | Attendance
        |--------------------------------------------------------------------------
        */

        'present_days',

        'leave_days',

        'absent_days',

        /*
        |--------------------------------------------------------------------------
        | Salary Structure
        |--------------------------------------------------------------------------
        */

        'basic_salary',

        'hra',

        'da',

        'ta',

        'bonus',

        'incentive',

        'other_allowance',

        /*
        |--------------------------------------------------------------------------
        | Deductions
        |--------------------------------------------------------------------------
        */

        'pf',

        'esi',

        'tds',

        'professional_tax',

        'other_deduction',

        /*
        |--------------------------------------------------------------------------
        | Final Salary
        |--------------------------------------------------------------------------
        */

        'gross_salary',

        'total_deduction',

        'net_salary'

    ];

    /*
    |--------------------------------------------------------------------------
    | User
    |--------------------------------------------------------------------------
    */

    public function user()
    {
        return $this->belongsTo(
            User::class
        );
    }
}